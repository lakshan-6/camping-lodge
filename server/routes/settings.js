import { Router } from 'express';
import { Settings } from '../models/index.js';
import { requireAdmin } from '../utils/auth.js';
import { mutate,audit,units } from '../utils/operations.js';
import { mailReady } from '../utils/mail.js';
import { bookingEmailConfigured } from '../utils/bookingEmail.js';
const emailSettings=()=>({emailConfigured:mailReady(),bookingEmailConfigured:bookingEmailConfigured()});
export const getSettings=async(session=null)=>(await Settings.findOne().session(session))||(await Settings.create([{}],{session}))[0];
const r=Router();
r.get('/',async(req,res,next)=>{try{const s=await getSettings();res.json({...s.toObject(),...emailSettings()});}catch(e){next(e);}});
r.put('/',requireAdmin,async(req,res,next)=>{try{res.json(await mutate(req,'settings.edit',async session=>{const s=await getSettings(session),before=s.toObject();s.set({businessName:req.body.businessName,phone:req.body.phone,address:req.body.address,graceMinutes:units(req.body.graceMinutes||0,true)});await s.save({session});await audit(session,req.user,'settings.edited',s._id,before,s);return {...s.toObject(),emailConfigured:mailReady()};}));}catch(e){next(e);}});
export default r;
